/*
    Se carga el rango con el correlativo por donde va Stellar, para que CG-POS siga desde ahí.
    Un rango ya agotado (el último llegó al final) entra desactivado: no sirve para emitir.
*/
INSERT INTO [SecuenciasEcf] ([Id], [CajaId], [Serie], [TipoComprobante], [Desde], [Hasta], [Ultimo], [VenceEn], [Activa], [ModificadoEn], [ModificadoPor])
SELECT NEXT VALUE FOR [SecuenciaSecuenciasEcf], k.Id, o.Serie, o.TipoComprobante, o.Desde, o.Hasta, o.Ultimo, o.VenceEn,
    CASE WHEN o.Ultimo >= o.Hasta THEN 0 ELSE 1 END, SYSDATETIMEOFFSET(), N'Migración'
FROM #Secuencias o
JOIN #Equivalencias e ON e.CajaStellar = o.CajaStellar
JOIN [Sucursales] s ON s.Codigo = e.SucursalCodigo
JOIN [Cajas] k ON k.SucursalId = s.Id AND k.Codigo = e.CajaCodigo
WHERE NOT EXISTS (
    SELECT 1 FROM [SecuenciasEcf] x
    WHERE x.CajaId = k.Id AND x.TipoComprobante = o.TipoComprobante AND x.Serie = o.Serie AND x.Desde = o.Desde);
GO

/* Rangos que no se cargaron porque su caja no está en la equivalencia o no existe en CG-POS. */
SELECT o.CajaStellar, o.TipoComprobante, o.Serie, o.Desde, o.Hasta, o.Ultimo,
       CASE WHEN e.CajaStellar IS NULL THEN 'La caja no está en #Equivalencias'
            ELSE 'No hay una caja ' + e.CajaCodigo + ' en la sucursal ' + e.SucursalCodigo END AS Motivo
FROM #Secuencias o
LEFT JOIN #Equivalencias e ON e.CajaStellar = o.CajaStellar
LEFT JOIN [Sucursales] s ON s.Codigo = e.SucursalCodigo
LEFT JOIN [Cajas] k ON k.SucursalId = s.Id AND k.Codigo = e.CajaCodigo
WHERE k.Id IS NULL;
GO

