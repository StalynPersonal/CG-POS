/*
    CG-POS · Datos migrados desde Stellar (rangos de e-NCF)
    Generado desde STELLAR.xlsx (Punta Cana) el 20/09/2026.

    ============================  LEA ESTO ANTES DE EJECUTAR  ============================

    Estos son los rangos de comprobantes fiscales que Stellar está usando AHORA MISMO, con el
    correlativo por donde va cada caja. Cargarlos en CG-POS significa que CG-POS seguirá numerando
    donde Stellar se quedó.

    Si los dos sistemas emiten a la vez con el mismo rango, se repiten e-NCF y eso es un problema
    fiscal con la DGII, no un detalle técnico. Ejecute esto solo cuando la caja de Stellar ya no vaya
    a facturar más, o pida rangos nuevos a la DGII para CG-POS y no use este archivo.

    Además, el correlativo que trae cada rango es el del día en que se exportó el Excel: si Stellar
    siguió facturando después, hay que volver a exportarlo antes de migrar.

    ======================================================================================

    Las cajas de Stellar van numeradas del 1 al 25. CG-POS tiene sus propias cajas, con su propio Id,
    así que hay que decir cuál es cuál en la tabla de equivalencias de abajo. Los rangos de una caja
    que no esté en esa tabla no se cargan y salen listados al final de la ejecución.
*/

